    add_p("Персональный компьютер (IBM-совместимый) в следующей минимальной конфигурации: процессор с тактовой частотой от 1.5 ГГц; оперативная память объемом не менее 1 ГБ; свободное дисковое пространство от 50 МБ; клавиатура, монитор с разрешением от 1024x768.", bold_prefix="3.4. Требования к составу и параметрам технических средств. ")

