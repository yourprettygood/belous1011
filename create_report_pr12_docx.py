    add_p(" персональный компьютер, среда программирования Microsoft Visual Studio 2019 / платформа .NET Framework 4.7.2 (C#).", bold_prefix="Оборудование, технические и программные средства: ")
    add_p(" Белоус.", bold_prefix="Выполнил: студент ")
    add_p(" 2 часа.", bold_prefix="Продолжительность занятия: ")

    # 3. Tasks
    add_heading("Задание", align=WD_ALIGN_PARAGRAPH.LEFT)
    add_p("1. Для выбранного программного продукта разработать техническое задание в строгом соответствии с ГОСТ 19.201-78, предполагая, что сначала разрабатывается ТЗ, а затем пишется программа по сформированному ТЗ.")
